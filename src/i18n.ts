const messages: Record<Language, Dictionary> = { ru, en };

/** Resolve the configured language; "auto" follows the VS Code display language. */
export function getLanguage(): Language {
    const configured = vscode.workspace
        .getConfiguration('stepik')
        .get<string>('language', 'auto');
    if (configured === 'ru' || configured === 'en') {
        return configured;
    }
    return vscode.env.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

export function localeFor(language: Language = getLanguage()): string {
    return language === 'ru' ? 'ru-RU' : 'en-US';
}

function interpolate(template: string, params?: Record<string, string | number>): string {
    if (!params) {
        return template;
    }
    return template.replace(/\{(\w+)\}/g, (match, key: string) => {
        const value = params[key];
        return value === undefined ? match : String(value);
    });
}

export function t(key: string, params?: Record<string, string | number>): string {
    const language = getLanguage();
    const template = messages[language][key] ?? messages.ru[key] ?? key;
    return interpolate(template, params);
}

export function raw(key: string, language: Language = getLanguage()): string {
    return messages[language][key] ?? messages.ru[key] ?? key;
}

/** Pick a Russian/English plural form from a `one|few|many` dictionary value. */
export function pluralize(
    count: number,
    key: string,
    language: Language = getLanguage()
): string {
    const forms = raw(key, language).split('|');
    if (language === 'en') {
        return count === 1 ? forms[0] || '' : forms[2] || forms[1] || forms[0] || '';
    }
    const abs = Math.abs(count) % 100;
    const last = abs % 10;
    if (abs > 10 && abs < 20) {
        return forms[2] || forms[0] || '';
    }
    if (last > 1 && last < 5) {
        return forms[1] || forms[0] || '';
    }
    if (last === 1) {
        return forms[0] || '';
    }
    return forms[2] || forms[0] || '';
}

/** Full dictionary plus locale metadata for embedding in a webview. */
export function webviewStrings(
    language: Language = getLanguage()
): Record<string, string> {
    return {
        ...messages[language],
        __lang: language,
        __locale: localeFor(language)
    };
}

/** Look up a date locale with an explicit language. */
export function dateLocale(language: Language = getLanguage()): string {
    return localeFor(language);
}
